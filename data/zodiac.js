// 生肖顺序（用于选择器）
const ZODIAC_ORDER = ZODIAC.map(z => z.key);

function getZodiac(key) {
  return ZODIAC.find(z => z.key === key) || null;
}

// 出生年份（公历，以春节近似为界，简化） → 生肖
function yearToZodiac(year) {
  // 1900 为鼠年（庚子），12 年一轮
  const base = 1900;
  const idx = ((year - base) % 12 + 12) % 12; // 0=鼠
  return ZODIAC[idx].key;
}

